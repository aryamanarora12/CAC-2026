// =========================================================
// CONVERT COURSE GROUPS INTO THE FORMAT USED BY
// CourseAutocomplete.jsx
// =========================================================

export const courses = courseGroups.flatMap((group) =>
  group.courses.map((name) => ({
    name,
    subject: group.subject,
    type: getCourseType(name)
  }))
);


// =========================================================
// AUTOMATICALLY DETERMINE COURSE TYPE
// =========================================================

function getCourseType(name) {

  if (name.startsWith("AP ")) {
    return "AP";
  }

  if (name.toLowerCase().includes("honors")) {
    return "Honors";
  }

  if (
    name.toLowerCase().includes("college") ||
    name.toLowerCase().includes("dual enrollment") ||
    name.toLowerCase().includes("dual credit")
  ) {
    return "College";
  }

  if (
    name.toLowerCase().includes("advanced") ||
    name.toLowerCase().includes("advanced placement")
  ) {
    return "Advanced";
  }

  return "Regular";
}

